library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library pll;
use pll.all;

entity telecran is
    port (
        -- FPGA
        i_clk_50: in std_logic;

        -- HDMI
        io_hdmi_i2c_scl       : inout std_logic;
        io_hdmi_i2c_sda       : inout std_logic;
        o_hdmi_tx_clk        : out std_logic;
        o_hdmi_tx_d          : out std_logic_vector(23 downto 0);
        o_hdmi_tx_de         : out std_logic;
        o_hdmi_tx_hs         : out std_logic;
        i_hdmi_tx_int        : in std_logic;
        o_hdmi_tx_vs         : out std_logic;

        -- KEYs
        i_rst_n : in std_logic;
		  
		-- LEDs
		o_leds : out std_logic_vector(9 downto 0);
		o_de10_leds : out std_logic_vector(7 downto 0);

		-- Coder
		i_left_ch_a : in std_logic;
		i_left_ch_b : in std_logic;
		i_left_pb : in std_logic;
		i_right_ch_a : in std_logic;
		i_right_ch_b : in std_logic;
		i_right_pb : in std_logic
    );
end entity telecran;

architecture rtl of telecran is
	component I2C_HDMI_Config 
		port (
			iCLK : in std_logic;
			iRST_N : in std_logic;
			I2C_SCLK : out std_logic;
			I2C_SDAT : inout std_logic;
			HDMI_TX_INT  : in std_logic
		);
	 end component;
	 
	component pll 
		port (
			refclk : in std_logic;
			rst : in std_logic;
			outclk_0 : out std_logic;
			locked : out std_logic
		);
	end component;

    constant h_res : natural := 720;
    constant v_res : natural := 480;

	signal s_clk_27 : std_logic;
	signal s_rst_n : std_logic;	-- holds reset as long as pll is not locked
	signal s_hdmi_hs   : std_logic;
	signal s_hdmi_vs   : std_logic;
	signal s_hdmi_de   : std_logic;
	signal s_x_counter : natural range 0 to (h_res-1);
	signal s_y_counter : natural range 0 to (v_res-1);
	
	-- positions encoder
	signal x_encoder_pos : natural range 0 to h_res-1;
	signal y_encoder_pos : natural range 0 to v_res-1;
	



	constant COLOR_DRAW : std_logic_vector(23 downto 0) := x"B22222"; 
	constant COLOR_BG : std_logic_vector(23 downto 0) := x"FFFFFF";
	
	    -- framebuffer 8-bit
    signal fb_data_out   : std_logic_vector(7 downto 0);  -- lecture depuis le port A (HDMI)
    signal fb_write_data : std_logic_vector(7 downto 0) := x"FF"; -- valeur à écrire (ex: x"FF" = drawn)
    signal fb_addr       : natural range 0 to h_res * v_res - 1;   -- adresse de lecture (port A)
    signal fb_write_en   : std_logic := '0';                       -- write enable for port B
		 
	
	signal clear_active : std_logic := '0';
	signal clear_addr   : natural range 0 to h_res*v_res-1 := 0;
	signal pb_left_prev : std_logic := '0';

	signal fb_we        : std_logic;

	signal fb_write_addr : natural range 0 to h_res*v_res-1;
	
	signal prev_x : natural range 0 to h_res-1 := 0;
	signal prev_y : natural range 0 to v_res-1 := 0;


begin
	o_leds <= (others => '0');
	o_de10_leds <= (others => '0');
	
	-- Frequency for HDMI is 27MHz generated by this PLL
	pll0 : component pll 
		port map (
			refclk => i_clk_50,
			rst => not(i_rst_n),
			outclk_0 => s_clk_27,
			locked => s_rst_n
		);

	-- Configures the ADV7513 for 480p
	I2C_HDMI_Config0 : component I2C_HDMI_Config 
		port map (
			iCLK => i_clk_50,
			iRST_N => i_rst_n,
			I2C_SCLK => io_hdmi_i2c_scl,
			I2C_SDAT => io_hdmi_i2c_sda,
			HDMI_TX_INT => i_hdmi_tx_int
	 );
	 
    -- Instanciation du HDMI controller
    hdmi_controler : entity work.hdmi_controler
        generic map (
            h_res  => h_res,
            v_res  => v_res,
            h_sync => 61,
            h_fp   => 58,
            h_bp   => 18,
            v_sync => 5,
            v_fp   => 30,
            v_bp   => 9
        )
        port map (
            i_clk           => s_clk_27,
            i_rst_n         => s_rst_n,
            o_hdmi_hs       => s_hdmi_hs,
            o_hdmi_vs       => s_hdmi_vs,
            o_hdmi_de       => s_hdmi_de,
            o_pixel_en      => open,
            o_pixel_address => open,
            o_x_counter     => s_x_counter,
            o_y_counter     => s_y_counter
        );

    -- Connexion aux sorties HDMI
    o_hdmi_tx_hs <= s_hdmi_hs;
    o_hdmi_tx_vs <= s_hdmi_vs;
    o_hdmi_tx_de <= s_hdmi_de;
    o_hdmi_tx_clk <= s_clk_27;
	 
	 encoder_h : entity work.encoder_draw
    generic map (POS_MAX => h_res-1)   -- 0 à 719
    port map (
        i_clk_50  => i_clk_50,
        i_rst_n   => s_rst_n,
        ENC_A     => i_left_ch_a,
        ENC_B     => i_left_ch_b,
        o_position=> x_encoder_pos
    );

	 encoder_v : entity work.encoder_draw
    generic map (POS_MAX => v_res-1)   -- 0 à 479
    port map (
        i_clk_50  => i_clk_50,
        i_rst_n   => s_rst_n,
        ENC_A     => i_right_ch_a,
        ENC_B     => i_right_ch_b,
        o_position=> y_encoder_pos
    );
	 
	----------
	process(i_clk_50)
begin
    if rising_edge(i_clk_50) then

        -- detecter le front montant du bouton gauche
        if i_left_pb = '1' and pb_left_prev = '0' then
            clear_active <= '1';
            clear_addr   <= 0;
        end if;
        pb_left_prev <= i_left_pb;

        -- état d'effacement
        if clear_active = '1' then
            fb_write_addr <= clear_addr;
            fb_write_data <= (others => '0');
            fb_we <= '1';
            
            if clear_addr < h_res*v_res-1 then
                clear_addr <= clear_addr + 1;
            else
                clear_active <= '0';
            end if;

        else
            -- dessin : écrire chaque cycle, entre la position précédente et actuelle
            fb_we <= '1';

            -- simple solution : dessiner juste le pixel courant
            fb_write_addr <= x_encoder_pos + y_encoder_pos*h_res;
            fb_write_data <= x"FF";

            -- stocker la position précédente
            prev_x <= x_encoder_pos;
            prev_y <= y_encoder_pos;
        end if;

    end if;
end process;

	----------
	 
    hdmi_fb : entity work.dpram
        generic map(
            mem_size   => h_res * v_res,
            data_width => 8
        )
        port map(
            i_clk_a => s_clk_27,                 -- port A : lecture by HDMI (27 MHz)
            i_clk_b => i_clk_50,                 -- port B : écriture (50 MHz)

            i_data_a => (others => '0'),         -- not used for writing on port A
            i_data_b => fb_write_data,           -- data to write on port B

            i_addr_a => fb_addr,                 -- address for HDMI read (natural)
			  i_addr_b => fb_write_addr,  -- <- use fb_write_addr now
			  i_we_a   => '0',
			  i_we_b   => fb_we,          -- <- use fb_we now

            o_q_a    => fb_data_out,
            o_q_b    => open
        );

	
	 
	fb_addr <= s_x_counter + s_y_counter * h_res;


	fb_write_en <= '1' when (s_x_counter = x_encoder_pos and s_y_counter = y_encoder_pos) else '0';

		
	-- o_hdmi_tx_d <= COLOR_DRAW when (fb_data_out = "1") else COLOR_BG;

	 -- test
    o_hdmi_tx_d <= fb_data_out & fb_data_out & fb_data_out;


    -- Tracé du pixel
	o_hdmi_tx_d <= x"B22222" when (s_x_counter = x_encoder_pos and s_y_counter = y_encoder_pos) else x"FFFFFF";


end architecture rtl;
